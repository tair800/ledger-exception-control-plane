"""Replay the committed cassette through the real proposal path (M6.2).

This module produces the proposals the gate scores. It does that by driving the **shipped**
pipeline — ``assemble_evidence`` → ``build_prompt`` → :class:`ReplayTransport` → the adapter's own
``propose`` — rather than by reading answers out of the cassette file. The distinction is the whole
point: reading the file would test the file, and what has to be protected from regression is the
code between the corpus and a validated :class:`TreatmentProposal`.

**What a score over this run does and does not measure.** The committed cassettes are
*synthesised*. ``tests/cassette_builder.py::stand_in_answer`` assigns a treatment by
``TreatmentCode[position % 4]`` — round-robin over the exceptions in sorted-id order — so agreement
with the golden labels is **arithmetic on two orderings, not judgement**. It would be exactly as
high if the model were a coin. So:

- This is a **reproduction gate**. It fails when evidence assembly, prompt construction, request
  fingerprinting, response parsing, or the scorer's arithmetic changes what comes out.
- It is **not a model-quality gate**, and the accuracy number in the baseline is **not an accuracy
  threshold**. There is no model in this run. `CLAUDE.md` §10 forbids inventing a metric, and a
  synthesised agreement rate presented as accuracy is the most available way to do that here.

:class:`~tests.evaluation.scorer.CassetteOrigin` is not hard-coded: it is read off the interactions
the cassette actually served, so the day a real capture is committed the reports re-describe
themselves rather than needing a constant edited.

**The set being scored is the canonical corpus's 13 exceptions**, generated at
``Profile.CANONICAL``, because that is what the committed cassette covers. The committed
``treatment-golden.jsonl`` is a different, larger artefact (``Profile.BULK``, 1200 instances) that
exists so the label *distribution* can be reported as a rate; its 250 records come from a different
corpus and share no identifier with these 13. Both are generated by the same function, from the same
seed, in the same identifier namespace.

**Nothing here can reach a provider.** No HTTP client is in the dependency graph, the only transport
is a replay over a committed file, and a cassette miss is a loud harness failure with no fallback to
a live call.
"""

from __future__ import annotations

import asyncio
import dataclasses
import hashlib
import pathlib
from typing import Any, Final

from ledger_exception_control_plane.fixtures.schema import Profile
from ledger_exception_control_plane.llm.cassette import (
    Cassette,
    Origin,
    ReplayTransport,
    load_cassette,
)
from ledger_exception_control_plane.llm.evidence import assemble_evidence
from ledger_exception_control_plane.llm.port import ProviderId
from ledger_exception_control_plane.llm.prompt import build_prompt
from ledger_exception_control_plane.matching import DEFAULT_POLICY
from tests.cassette_builder import CANONICAL_CASSETTE, CORPUS_LINES, PROVIDERS, corpus_subjects
from tests.evaluation.golden import GOLDEN_SEED, GoldenSet, build_golden_set
from tests.evaluation.scorer import CassetteOrigin, Proposal, Score, score

__all__ = [
    "REPLAY_CASSETTE",
    "REPLAY_INSTANCES",
    "REPLAY_PROFILE",
    "ProviderReplay",
    "cassette_digest",
    "origin_of",
    "replay_all",
    "replay_golden_set",
    "score_replay",
]

#: The cassette the gate replays. The committed one, deliberately: a gate over a file generated at
#: run time would pass by construction.
REPLAY_CASSETTE: Final = CANONICAL_CASSETTE

#: The corpus shape the cassette was built from, restated here so a mismatch is a named failure
#: rather than a wall of cassette misses. Imported from the builder where possible.
REPLAY_PROFILE: Final = Profile.CANONICAL
REPLAY_INSTANCES: Final = CORPUS_LINES

#: How the two cassette origins map onto what a score may claim.
_ORIGIN: Final = {
    Origin.SYNTHESISED: CassetteOrigin.SYNTHESISED,
    Origin.CAPTURED: CassetteOrigin.CAPTURED,
}


@dataclasses.dataclass(frozen=True, slots=True)
class ProviderReplay:
    """One provider's replay of the whole corpus, and the provenance of the answers."""

    provider: ProviderId
    model_id: str
    model_version: str

    #: Where the served responses came from. Read from the cassette, never assumed.
    origin: CassetteOrigin

    #: One proposal per exception, keyed by the corpus row identifier — the same key the golden set
    #: uses. Sorted, so a rendered baseline is stable.
    proposals: tuple[Proposal, ...]

    #: The cassette ids that answered, in call order. Carried so a caller can assert that each
    #: answer came from its own recording rather than from one recording serving everything.
    served: tuple[str, ...]


def origin_of(cassette: Cassette, provider: ProviderId) -> CassetteOrigin:
    """What a score over this provider's interactions is allowed to claim.

    Refuses a mixed file rather than picking the more flattering member. A cassette holding one
    captured response among twelve synthesised ones cannot be described by either word, and the
    honest options are to refuse or to report per-interaction — refusing is the one that cannot be
    misread.
    """
    origins = {item.origin for item in cassette.interactions if item.provider is provider}
    if not origins:
        raise ValueError(f"{REPLAY_CASSETTE.name} holds no interactions for {provider.value}")
    if len(origins) > 1:
        raise ValueError(
            f"{REPLAY_CASSETTE.name} mixes {sorted(o.value for o in origins)} for "
            f"{provider.value}; a single score cannot describe both, so split the file or the run"
        )
    return _ORIGIN[origins.pop()]


async def _replay_provider(
    provider: ProviderId, adapter: type[Any], cassette: Cassette
) -> ProviderReplay:
    """Drive every corpus exception through one adapter, answered from the cassette.

    The transport is constructed once for the whole run, so ``served`` is the ledger of which
    recording answered which call — which is what makes "each answer came from its own recording"
    checkable rather than assumed.
    """
    transport = ReplayTransport(cassette)
    proposer = adapter(transport)

    proposals: list[Proposal] = []
    for subject, candidates in corpus_subjects():
        pack = assemble_evidence(subject, candidates, DEFAULT_POLICY)
        prompt = build_prompt(subject, pack)
        proposal = await proposer.propose(prompt)
        proposals.append(
            Proposal(
                exception_id=str(subject.exception_id),
                treatment=proposal.treatment,
                abstained=proposal.abstained,
            )
        )

    return ProviderReplay(
        provider=provider,
        model_id=proposer.model_id,
        model_version=proposer.model_version,
        origin=origin_of(cassette, provider),
        proposals=tuple(sorted(proposals, key=lambda p: p.exception_id)),
        served=tuple(transport.served),
    )


def replay_all(cassette_path: pathlib.Path = REPLAY_CASSETTE) -> tuple[ProviderReplay, ...]:
    """Replay the corpus through every provider the builder covers.

    Synchronous on purpose. The gate is a command-line check and a unit test; making its entry
    point async would push an event loop into both for no benefit, since the transport does no I/O.
    """
    cassette = load_cassette(cassette_path)
    return tuple(
        asyncio.run(_replay_provider(provider, adapter, cassette))
        for provider, adapter in PROVIDERS
    )


def replay_golden_set() -> GoldenSet:
    """The labelled set the replayed proposals are graded against.

    The canonical corpus, at the same seed as everything else, so the identifiers join. Built
    rather than loaded: the committed file is the ``BULK`` set, which describes a different corpus.
    """
    return build_golden_set(seed=GOLDEN_SEED, profile=REPLAY_PROFILE, instances=REPLAY_INSTANCES)


def score_replay(run: ProviderReplay, golden: GoldenSet | None = None) -> Score:
    """Grade one provider's replay. The origin travels from the cassette into the score."""
    return score(golden or replay_golden_set(), run.proposals, origin=run.origin)


def cassette_digest(cassette_path: pathlib.Path = REPLAY_CASSETTE) -> str:
    """SHA-256 of the committed cassette's bytes, normalised to LF.

    Recorded in the baseline so a changed cassette fails the gate with "the cassette changed"
    rather than with a shifted confusion matrix a reader has to reverse-engineer. Normalised
    because the repository checks text out platform-native and a digest that changed with the
    checkout would be a false alarm on every Windows machine.
    """
    return hashlib.sha256(cassette_path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
