#: Bumped when the *shape* of a record changes, or when the meaning of its key does. A committed
#: file at an older version is a failure rather than something to migrate: regenerating costs a
#: second.
#:
#: ``2`` is the identity migration described in the module docstring. The field list did not change;
#: ``exception_id`` stopped being a locally derived ``uuid5`` and became the corpus row's own
#: identifier, so every one of the 250 keys is different from version 1's. That is a bigger change
#: than adding a field, and a version that only tracked the field list would have let a stale file
#: load with keys that join to nothing.
GOLDEN_SCHEMA_VERSION: Final = "2"

#: The committed artefact. JSONL because it is append-friendly, line-diffable in review, and the
#: format §20 names.
GOLDEN_PATH: Final = (
    pathlib.Path(__file__).resolve().parents[1] / "golden" / "treatment-golden.jsonl"
)

#: The seed and shape the golden set is generated from. The same seed as the committed corpus, and
#: ``BULK`` rather than ``CANONICAL`` because a one-of-each corpus cannot support a rate: an
#: abstention rate over four records is not a measurement.
GOLDEN_SEED: Final = 20260829
GOLDEN_PROFILE: Final = Profile.BULK

#: 1200 scenario instances, which yields 250 labelled exceptions.
#:
#: Chosen against a measured property rather than picked. The label distribution is stable at every
#: scale tried — 84.6% ``ESCALATE`` at 200 instances, 85.8% at 600, 85.6% at 1200, 85.5% at 2400 —
#: so the size buys sample size and nothing else, and the number was set where the file is still
#: small enough for a person to read the hold-out slice by hand. **That stability is itself the most
#: important fact about this set**: the imbalance is structural, not a sampling artefact, because
#: only two of the four reachable classes are priceable at all. A scorer reporting bare accuracy
#: over it would credit a model that answers ``ESCALATE`` to everything with 85.6%, which is why
#: :mod:`tests.evaluation.scorer` reports that baseline beside every accuracy figure and measures
#: the priceable classes separately.
GOLDEN_INSTANCES: Final = 1200

#: Every Nth record, in the set's own stable order, is held out for human confirmation.
#:
#: A fixed stride rather than a random sample, deliberately. §20 wants a hold-out *slice*, and the
#: property that matters is that it is the same slice on every run — a seeded shuffle would also
#: give that, but a stride can be checked by eye against the file, which a reviewer confirming
#: labels by hand will want. It also spreads across the file's ordering, so the slice cannot consist
#: entirely of one classification.
HOLD_OUT_EVERY: Final = 10


@dataclasses.dataclass(frozen=True, slots=True)
class GoldenRecord:
    """One labelled exception: what the system concluded, and what the right treatment is.

    The first block is the *state a model is asked about* — everything the evidence pack would be
    assembled from. The second block is the label. Nothing here comes from the corpus's own
    construction metadata.
    """

    #: The settlement line's own identifier, taken from the corpus row. The key, and deliberately
    #: the *same* key the cassette-covered subjects carry — a golden record and the proposal made
    #: about it must be joinable, or neither can grade the other.
    exception_id: str

    # --- what the deterministic layers concluded -------------------------------------------
    classification: str
    rule_id: str
    amount: str
    currency: str
    value_date: str
    settlement_period: str
    originating_period: str | None
    transaction_type: str | None
    has_merchant_reference: bool

    # --- the label -------------------------------------------------------------------------
    expected_treatment: str
    label_rule: str
    label_source: str
    label_why: str
    escalation_is_correct: bool
    held_out: bool

    def as_json(self) -> str:
        return json.dumps(dataclasses.asdict(self), sort_keys=True, separators=(",", ":"))


@dataclasses.dataclass(frozen=True, slots=True)
class GoldenSet:
    """The whole set, with the provenance needed to regenerate it exactly."""

    schema_version: str
    seed: int
    profile: str
    instances: int
    records: tuple[GoldenRecord, ...]

    @property
    def by_classification(self) -> dict[str, int]:
        return dict(sorted(collections.Counter(r.classification for r in self.records).items()))

    @property
    def by_expected_treatment(self) -> dict[str, int]:
        return dict(sorted(collections.Counter(r.expected_treatment for r in self.records).items()))

    @property
    def hold_out(self) -> tuple[GoldenRecord, ...]:
        return tuple(record for record in self.records if record.held_out)

    @property
    def human_labelled(self) -> tuple[GoldenRecord, ...]:
        """Records a person has confirmed. Empty until one does, and reported as empty."""
        return tuple(
            record for record in self.records if record.label_source == LabelSource.HUMAN.value
        )


def _originating_period(
    subject: SettlementMovement, movements: list[SettlementMovement]
) -> str | None:
    """The period of the reconciled movement this one exactly reverses, if there is exactly one.

    The same derivation ``demo/snapshot.py`` performs, from production fields only — the merchant's
    reference, the currency, the match state and an exact negation. Duplicated rather than imported
    because it is private to that module and importing a private helper across the test fence would
    couple the golden set to a shipped module's internals; a test asserts the two agree on the
    committed corpus, which is the property that actually matters.
    """
    if subject.merchant_reference is None:
        return None
    offsets = [
        other
        for other in movements
        if other.id != subject.id
        and other.matched
        and other.merchant_reference == subject.merchant_reference
        and other.currency == subject.currency
        and other.amount == -subject.amount
    ]
    if len(offsets) != 1:
        return None
    return accounting_period(offsets[0].value_date)


def build_golden_set(
    *,
    seed: int = GOLDEN_SEED,
    profile: Profile = GOLDEN_PROFILE,
    instances: int = GOLDEN_INSTANCES,
) -> GoldenSet:
    """Run the deterministic pipeline over a seeded corpus and label every residual it leaves.

    Chained, not recomputed: the corpus rows are what the matcher sees, what the matcher leaves is
    what the classifier reads, and what the classifier decided is what gets labelled.

    **The lines come from the corpus rows, in their own identifier namespace.** That is the same
    thing ``tests/cassette_builder.py::corpus_subjects`` does, deliberately, and it is what makes
    the two artefacts joinable — see the module docstring for what the first version did instead
    and what it cost. Nothing here reads a construction label; a row carries one, and this module
    never touches it.
    """
    generated = generate(seed, profile, instances)

    rows: list[SettlementLineRecord] = [
        row for batch in generated.corpus.batches for row in batch.lines
    ]

    candidates: list[CandidateLine] = []
    line_of: dict[uuid.UUID, SettlementLineRecord] = {}
    for row in rows:
        candidates.append(
            CandidateLine(
                id=row.id,
                line_number=row.line_number,
                amount=row.amount,
                currency=row.currency,
                value_date=row.value_date,
            )
        )
        line_of[row.id] = row

    entries = [
        CandidateEntry(
            id=entry.id,
            external_ref=entry.external_ref,
            amount=entry.amount,
            currency=entry.currency,
            booked_on=entry.booked_at.date(),
        )
        for entry in generated.corpus.ledger_entries
    ]

    outcome = match(candidates, entries, DEFAULT_POLICY)
    matched_lines = {pair.line_id for pair in outcome.matches}

    movements = [
        SettlementMovement(
            id=candidate.id,
            merchant_reference=line_of[candidate.id].merchant_reference,
            movement=movement_type(line_of[candidate.id].transaction_type),
            amount=candidate.amount,
            currency=candidate.currency,
            value_date=candidate.value_date,
            matched=candidate.id in matched_lines,
        )
        for candidate in candidates
    ]
    by_movement = {movement.id: movement for movement in movements}
    decisions = classify([m for m in movements if not m.matched], movements)

    # Sorted by exception id so the file's order is a property of the data rather than of the
    # order two loops happened to run in — which is what makes the hold-out stride stable and the
    # drift check meaningful.
    records: list[GoldenRecord] = []
    for index, decision in enumerate(sorted(decisions, key=lambda d: str(d.line_id))):
        movement = by_movement[decision.line_id]
        line = line_of[decision.line_id]
        originating = _originating_period(movement, movements)
        label = label_for(decision.classification, originating_period=originating)
        records.append(
            GoldenRecord(
                exception_id=str(decision.line_id),
                classification=decision.classification.value,
                rule_id=decision.rule_id.value,
                amount=str(movement.amount),
                currency=movement.currency,
                value_date=movement.value_date.isoformat(),
                settlement_period=accounting_period(movement.value_date),
                originating_period=originating,
                transaction_type=line.transaction_type,
                has_merchant_reference=line.merchant_reference is not None,
                expected_treatment=label.treatment.value,
                label_rule=label.rule.value,
                label_source=label.source.value,
                label_why=label.why,
                escalation_is_correct=label.escalation_is_correct,
                held_out=index % HOLD_OUT_EVERY == 0,
            )
        )

    return GoldenSet(
        schema_version=GOLDEN_SCHEMA_VERSION,
        seed=seed,
        profile=profile.value,
        instances=instances,
        records=tuple(records),
    )


def render_golden_set(golden: GoldenSet) -> str:
    """The committed file's exact bytes: one header line, then one record per line.

    A header line rather than a sidecar file, so the provenance needed to regenerate the set cannot
    be separated from the set.
    """
    header = json.dumps(
        {
            "schema_version": golden.schema_version,
            "seed": golden.seed,
            "profile": golden.profile,
            "instances": golden.instances,
            "records": len(golden.records),
            "held_out": len(golden.hold_out),
            "by_classification": golden.by_classification,
            "by_expected_treatment": golden.by_expected_treatment,
        },
        sort_keys=True,
        separators=(",", ":"),
    )
    return "\n".join([header, *(record.as_json() for record in golden.records)]) + "\n"


def load_golden_set(path: pathlib.Path = GOLDEN_PATH) -> GoldenSet:
    """Read the committed set. Raises rather than repairing anything it does not recognise."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        raise ValueError(f"{path} is empty")

    header = json.loads(lines[0])
    if header.get("schema_version") != GOLDEN_SCHEMA_VERSION:
        raise ValueError(
            f"{path} is schema version {header.get('schema_version')!r} and this code reads "
            f"{GOLDEN_SCHEMA_VERSION!r}; regenerate it rather than migrating it"
        )

    records = tuple(GoldenRecord(**json.loads(line)) for line in lines[1:])
    if len(records) != header["records"]:
        raise ValueError(f"{path} declares {header['records']} records and holds {len(records)}")

    return GoldenSet(
        schema_version=header["schema_version"],
        seed=header["seed"],
        profile=header["profile"],
        instances=header["instances"],
        records=records,
    )


def amount_of(record: GoldenRecord) -> decimal.Decimal:
    """The record's amount as a ``Decimal``.

    Stored as a string and parsed on demand, never as a float: JSON has one number type and it is
    binary floating point, so a monetary value written as a JSON number would be a rounding error
    committed to a file. The same reason `M1.1` gave for the column type.
    """
    return decimal.Decimal(record.amount)


def classification_of(record: GoldenRecord) -> ExceptionClassification:
    return ExceptionClassification(record.classification)


def expected_treatment_of(record: GoldenRecord) -> TreatmentCode:
    return TreatmentCode(record.expected_treatment)


def label_rule_of(record: GoldenRecord) -> LabelRule:
    return LabelRule(record.label_rule)
